"""Builds evaluation/5.1a/output/tables.md (readable extracts of the CSVs; every number is copied by code, none typed)."""
from pathlib import Path
import pandas as pd

OUT = Path(__file__).resolve().parent / "output"


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    out = ["# 5.1a tables (generated by make_tables.py from the CSVs in this folder; E-dL = working CoM, unfiltered unless stated)\n"]
    nf = pd.read_csv(OUT / "noise_free_per_clip.csv")
    x = nf[(nf.com == "edl") & (nf["filter"] == "none")].copy()
    x["LDLJ median [Q1, Q3]"] = x.apply(lambda r: f"{r.ldlj_median:.2f} [{r.ldlj_q1:.2f}, {r.ldlj_q3:.2f}]", axis=1)
    x["SPARC median [Q1, Q3]"] = x.apply(lambda r: f"{r.sparc_median:.2f} [{r.sparc_q1:.2f}, {r.sparc_q3:.2f}]", axis=1)
    out += ["## 1. Noise-free LDLJ and SPARC per clip (descriptive; rank 1 = smoothest = highest value)\n",
            md(x[["duration_s", "clip", "n_windows", "LDLJ median [Q1, Q3]", "rank_ldlj_1smoothest", "SPARC median [Q1, Q3]", "rank_sparc_1smoothest"]]), ""]
    a = pd.read_csv(OUT / "com_agreement_and_clip_spread.csv")
    out += ["## 2. Range of the five clip medians (noise-free) and E-dL versus proxy A agreement (unfiltered)\n",
            md(a[a["filter"] == "none"][["metric", "duration_s", "range_of_clip_medians_edl", "range_of_clip_medians_A", "rank_edl", "rank_A",
                                         "spearman_rank_edl_vs_A", "median_window_diff_A_minus_edl"]]), ""]
    n = pd.read_csv(OUT / "noise_effect.csv")
    y = n[(n.com == "edl") & (n.scope == "ALL") & (n["class"] == "all") & (n["filter"] == "none")]
    out += ["## 3. Change from added noise alone (median over windows of the seed-mean change from the same window's noise-free value; unfiltered)\n",
            md(y.pivot_table(index=["metric", "duration_s"], columns="noise_level_torso", values="median_delta").round(2).reset_index()), "",
            "Median over windows of the sd across the 20 seeds:\n",
            md(y.pivot_table(index=["metric", "duration_s"], columns="noise_level_torso", values="median_seed_sd").round(2).reset_index()), ""]
    f = pd.read_csv(OUT / "filter_effect.csv")
    z = f[(f.com == "edl") & (f["class"] == "all")]
    out += ["## 4. Change from filtering alone (noise-free; median over windows of filtered minus unfiltered)\n",
            md(z.pivot_table(index=["metric", "filter"], columns="duration_s", values="median_delta_vs_unfiltered").round(2).reset_index()), ""]
    r = pd.read_csv(OUT / "ranking_stability.csv")
    r.columns = ["com", "metric", "dur", "filter", "lv", "ns", "ref_none", "ref_same", "rho_none", "rmin_none", "id_none", "rho_same", "rmin_same", "id_same"]
    q = r[(r.com == "edl") & (r["filter"] == "none") & (r.lv > 0)]
    out += ["## 5. Clip order under added noise (unfiltered): mean Spearman rho of the five-clip order against the noise-free order, and share of the 20 seeds with an identical order\n",
            md(q.pivot_table(index=["metric", "dur"], columns="lv", values="rho_none").round(2).reset_index()), "",
            md(q.pivot_table(index=["metric", "dur"], columns="lv", values="id_none").round(2).reset_index()), ""]
    q2 = r[(r.com == "edl") & (r.lv == 0)]
    out += ["## 6. Clip order under filtering alone (noise-free): Spearman rho against the unfiltered order\n",
            md(q2.pivot_table(index=["metric", "filter"], columns="dur", values="rho_none").round(2).reset_index()), ""]
    s = pd.read_csv(OUT / "slow_vs_fast.csv")
    s["abs_slow"] = s.noisefree_median_slow + s.median_delta_slow
    s["abs_fast"] = s.noisefree_median_fast + s.median_delta_fast
    s["gap_slow_minus_fast_at_noise"] = s.abs_slow - s.abs_fast
    t = s[(s.com == "edl") & (s.duration_s == 1) & (s["filter"].isin(["none", "sg_13f", "bw_6Hz"]))]
    out += ["## 7. Slow versus fast windows, 1 s (n slow = n fast = 63 windows; slow-minus-fast gap in absolute score at each noise level; negative = slow scored less smooth)\n",
            md(t.pivot_table(index=["metric", "filter"], columns="noise_level_torso", values="gap_slow_minus_fast_at_noise").round(2).reset_index()), "",
            "Noise-free gap (slow minus fast) for the same rows: " + "; ".join(f"{m}/{fl}: {g:.2f}" for (m, fl), g in
                 t[t.noise_level_torso == 0.0025].set_index(["metric", "filter"]).eval("noisefree_median_slow - noisefree_median_fast").items()), ""]
    c = pd.read_csv(OUT / "sparc_cutoff_at_cap.csv")
    w = c[(c.com == "edl") & (c.duration_s == "all")]
    out += ["## 8. Share of windows where SPARC's adaptive cut-off is the 10 Hz cap, by filter and noise level\n",
            md(w.pivot_table(index="filter", columns="noise_level_torso", values=w.columns[-1]).round(2).reset_index()), ""]
    p = pd.read_csv(OUT / "sparc_parameter_sweep.csv")
    p = p[["setting", "amp_threshold", "fc_hz", "padlevel", "duration_s", "noisefree_median_by_clip(2412 2416 2417 2419 2420)", "rank_by_clip",
           "spearman_clip_order_vs_reference_setting", "median_delta_vs_reference_setting_noisefree", "mean_spearman_vs_reference_noisefree_order@0.005"]]
    p.columns = ["setting", "amp_th", "fc_Hz", "padlevel", "dur_s", "clip medians (2412 2416 2417 2419 2420)", "rank by clip", "rho vs reference order",
                 "median change vs reference value", "mean rho at noise 0.005"]
    out += ["## 9. SPARC one-at-a-time sweep (E-dL, unfiltered, noise-free unless stated; all 12 settings, all three durations)\n", md(p), ""]
    (OUT / "tables.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
