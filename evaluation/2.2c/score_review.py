"""
Unblinds the 2.2c blind review (D-026 addendum, 2026-11-26 later): joins judgements.csv with key.csv and applies the author's mapping.
Writes evaluation/2.2c/random_review/scored_windows.csv and scored_summary.md. Re-judges nothing; changes no status.
Mapping (author): a panel is off if listed in off_panels (jitter does not count). Compare the panel showing A_proxy with the panel showing
the candidate (EdL_c0.5, and separately EdLfill_c0.5): worse = candidate off and A not; better = A off and candidate not; equal = both or
neither. Fail flag = a jump, dropout or wrong place marked on the candidate panel and not on A's.
Rule (E-dL only, each set separately): worse < better AND fail count = 0.
"""
import csv
from pathlib import Path

D = Path(__file__).resolve().parent / "random_review"
SETS = {"random": [f"R{i:02d}" for i in range(1, 21)], "stress": [f"S{i:02d}" for i in range(1, 11)]}
CANDS = ["A_proxy", "EdL_c0.5", "F_full", "EdLfill_c0.5"]


def main():
    key = {r["window_id"]: {f"P{i}": r[f"P{i}"] for i in range(1, 5)} for r in csv.DictReader(open(D / "key.csv"))}
    jud = {r["window_id"]: r for r in csv.DictReader(open(D / "judgements.csv"))}
    split = lambda x: [p for p in x.split(";") if p]
    rows, tally = [], {}
    for sname, ids in SETS.items():
        for cand in ("EdL_c0.5", "EdLfill_c0.5"):
            tally[(sname, cand)] = {"better": [], "worse": [], "equal": [], "fail": []}
        for w in ids:
            k, j = key[w], jud[w]
            panel_of = {c: p for p, c in k.items()}
            off = {k[p]: p in split(j["off_panels"]) for p in k}
            jit = [k[p] for p in split(j["jitter_panels"])]
            flags = {c: any(j[f"{panel_of[c]}_{t}"] == "1" for t in ("jump", "dropout", "wrong_place")) for c in CANDS}
            row = {"set": sname, "window": w, "P1": k["P1"], "P2": k["P2"], "P3": k["P3"], "P4": k["P4"],
                   "off_candidates": ";".join(c for c in CANDS if off[c]), "jitter_candidates": ";".join(jit),
                   "best_panel": j["most_plausible_panel"], "best_candidate": k[j["most_plausible_panel"]] if j["most_plausible_panel"] else ""}
            for cand in ("EdL_c0.5", "EdLfill_c0.5"):
                if off[cand] and not off["A_proxy"]:
                    res = "worse"
                elif off["A_proxy"] and not off[cand]:
                    res = "better"
                else:
                    res = "equal"
                fail = flags[cand] and not flags["A_proxy"]
                row[f"{cand}_vs_A"] = res + ("+FAIL" if fail else "")
                tally[(sname, cand)][res].append(w)
                if fail:
                    tally[(sname, cand)]["fail"].append(w)
            rows.append(row)
    with open(D / "scored_windows.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n"); w.writeheader(); w.writerows(rows)
    L = ["# 2.2c blind review: unblinded result (generated by score_review.py; mapping and rule in the D-026 addendum; nothing re-judged, nothing changed)\n"]
    for sname in SETS:
        L.append(f"## {sname} set ({len(SETS[sname])} windows)\n")
        L.append("| comparison with A | better | worse | equal | fail flags |\n|---|---|---|---|---|")
        for cand in ("EdL_c0.5", "EdLfill_c0.5"):
            t = tally[(sname, cand)]
            L.append(f"| {cand} | {len(t['better'])} | {len(t['worse'])} | {len(t['equal'])} | {len(t['fail'])} |")
        t = tally[(sname, "EdL_c0.5")]
        met = len(t["worse"]) < len(t["better"]) and not t["fail"]
        L.append(f"\nRule for E-dL (worse < better and fail = 0) on the {sname} set: **{'met' if met else 'not met'}** (worse {len(t['worse'])}, better {len(t['better'])}, fail {len(t['fail'])}).")
        for cand in ("EdL_c0.5", "EdLfill_c0.5"):
            t = tally[(sname, cand)]
            L.append(f"- {cand}: better in {', '.join(t['better']) or 'none'}; worse in {', '.join(t['worse']) or 'none'}")
        L.append("\nOff panels by candidate (counts over the windows of this set):")
        for c in CANDS:
            ws = [r["window"] for r in rows if r["set"] == sname and c in r["off_candidates"].split(";")]
            L.append(f"- {c}: {len(ws)} ({', '.join(ws) or 'none'})")
        L.append("\nJitter panels by candidate:")
        for c in CANDS:
            ws = [r["window"] for r in rows if r["set"] == sname and c in r["jitter_candidates"].split(";")]
            L.append(f"- {c}: {len(ws)} ({', '.join(ws) or 'none'})")
        L.append("")
    L.append("## Windows where the author named a best panel\n")
    for r in rows:
        if r["best_panel"]:
            L.append(f"- {r['window']}: {r['best_panel']} = {r['best_candidate']}")
    L.append("\n## Per-window table\n\n| window | P1 | P2 | P3 | P4 | off | jitter | EdL vs A | EdLfill vs A |\n|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        L.append(f"| {r['window']} | {r['P1']} | {r['P2']} | {r['P3']} | {r['P4']} | {r['off_candidates']} | {r['jitter_candidates']} | {r['EdL_c0.5_vs_A']} | {r['EdLfill_c0.5_vs_A']} |")
    (D / "scored_summary.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
