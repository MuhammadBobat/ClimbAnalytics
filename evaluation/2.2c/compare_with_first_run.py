"""
2.2c on the D-030 gap-filled data against the first (raw, gated-lock) run: coverage, defined-to-None per 1,000 frames, position
difference to F, jitter on the common support (summary.csv of both). Descriptive; nothing is chosen. Written next to the new run:
    evaluation/2.2c/output_full_lock1_d030/comparison_with_first_run.csv and .md
The common support of the new run includes the extra candidate EdLfill_c0.5 (all candidates defined), so the two runs' common-support
jitter use different frame sets (counts given); the position difference to F uses each run's own F (F is defined on more frames after
filling), counts given.

Usage: python3 evaluation/2.2c/compare_with_first_run.py
"""
import csv
from pathlib import Path

OLD = Path("evaluation/2.2c/output_full_lock1")
NEW = Path("evaluation/2.2c/output_full_lock1_d030")
COLS = ["n_defined", "coverage", "defined_to_none_per_1000_frames", "n_defined_runs", "n_shared_with_f", "pos_px_mean", "pos_torso_mean",
        "jitter_common_n", "jitter_common_mean", "jitter_own_mean", "speed_vs_f_pearson"]


def load(p):
    with open(p / "summary.csv", newline="") as f:
        return {(r["clip"], r["candidate"]): r for r in csv.DictReader(f)}


def fl(x):
    return float(x) if x not in ("", None) else None


def main():
    old, new = load(OLD), load(NEW)
    scopes = list(dict.fromkeys(k[0] for k in new))
    cands = list(dict.fromkeys(k[1] for k in new))
    rows, header = [], ["scope", "candidate"] + [f"{c}_first" for c in COLS] + [f"{c}_filled" for c in COLS]
    for sc in scopes:
        for cand in cands:
            a, b = old.get((sc, cand)), new[(sc, cand)]
            rows.append([sc, cand] + [(a[c] if a else "") for c in COLS] + [b[c] for c in COLS])
    with open(NEW / "comparison_with_first_run.csv", "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n"); w.writerow(header); w.writerows(rows)
    md = ["# 2.2c on D-030 gap-filled data against the first (raw) run — ALL five clips (generated by compare_with_first_run.py)\n",
          "first = evaluation/2.2c/output_full_lock1; filled = evaluation/2.2c/output_full_lock1_d030. Descriptive only.\n"]
    for title, cols in (("Coverage and continuity", ["n_defined", "coverage", "defined_to_none_per_1000_frames", "n_defined_runs"]),
                        ("Position difference to F (each run's own F)", ["n_shared_with_f", "pos_px_mean", "pos_torso_mean"]),
                        ("Jitter (torso lengths per frame^2)", ["jitter_common_n", "jitter_common_mean", "jitter_own_mean"])):
        md += [f"## {title}\n", "| candidate | " + " | ".join(f"{c} first | {c} filled" for c in cols) + " |", "|" + "---|" * (1 + 2 * len(cols))]
        for cand in cands:
            a, b = old.get(("ALL", cand)), new[("ALL", cand)]
            md.append(f"| {cand} | " + " | ".join(f"{(a[c] if a else '—')} | {b[c]}" for c in cols) + " |")
        md.append("")
    # per clip coverage / defined-to-none of the working CoM, A and F
    md += ["## Per clip: coverage and defined-to-None per 1,000 frames (A, working CoM EdL_c0.5, F, extra EdLfill_c0.5)\n",
           "| clip | candidate | coverage first | filled | defined-to-None first | filled |", "|---|---|---|---|---|---|"]
    for sc in scopes:
        if sc == "ALL":
            continue
        for cand in ("A_proxy", "EdL_c0.5", "F_full", "EdLfill_c0.5"):
            a, b = old.get((sc, cand)), new[(sc, cand)]
            md.append(f"| {sc} | {cand} | {a['coverage'] if a else '—'} | {b['coverage']} | "
                      f"{a['defined_to_none_per_1000_frames'] if a else '—'} | {b['defined_to_none_per_1000_frames']} |")
    # same-frames jitter: the first run's common support (all 13 candidates' jitter defined there), in both runs
    clips = [c for c in scopes if c != "ALL"]
    labs = list(dict.fromkeys(k[1] for k in old))
    sums = {l: [0.0, 0.0, 0] for l in cands}
    for clip in clips:
        d = Path(clip).stem
        fo = list(csv.DictReader(open(OLD / d / "frames.csv", newline="")))
        fn = list(csv.DictReader(open(NEW / d / "frames.csv", newline="")))
        for ro, rn in zip(fo, fn):
            if all(ro[f"{l}_jitter_torso"] != "" for l in labs) and all(rn[f"{l}_jitter_torso"] != "" for l in labs):
                for l in labs:
                    sums[l][0] += float(ro[f"{l}_jitter_torso"]); sums[l][1] += float(rn[f"{l}_jitter_torso"]); sums[l][2] += 1
    md += ["## Jitter on the SAME frames (the 13 first-run candidates' common support in the first run, also defined in the filled run)\n",
           "| candidate | n frames | mean jitter first | mean jitter filled |", "|---|---|---|---|"]
    for l in labs:
        n = sums[l][2]
        md.append(f"| {l} | {n} | {sums[l][0] / n:.4f} | {sums[l][1] / n:.4f} |")
    md.append("")
    # frames that are common-support only in the filled run
    new_only = {l: [0.0, 0] for l in cands}
    for clip in clips:
        d = Path(clip).stem
        fo = list(csv.DictReader(open(OLD / d / "frames.csv", newline="")))
        fn = list(csv.DictReader(open(NEW / d / "frames.csv", newline="")))
        for ro, rn in zip(fo, fn):
            in_old = all(ro[f"{l}_jitter_torso"] != "" for l in labs)
            in_new = all(rn[f"{l}_jitter_torso"] != "" for l in cands)
            if in_new and not in_old:
                for l in cands:
                    new_only[l][0] += float(rn[f"{l}_jitter_torso"]); new_only[l][1] += 1
    md += ["## Jitter on the frames that are common support ONLY in the filled run (frames made usable by the gap filling)\n",
           "| candidate | n frames | mean jitter filled |", "|---|---|---|"]
    for l in cands:
        md.append(f"| {l} | {new_only[l][1]} | {new_only[l][0] / new_only[l][1]:.4f} |")
    md.append("")
    # triage
    def tri(p):
        with open(p / "triage.csv", newline="") as f:
            return {r["candidate"]: r for r in csv.DictReader(f)}
    to, tn = tri(OLD), tri(NEW)
    md += ["", "## Triage (same rule, chosen after the first run; not pre-registered)\n",
           f"first-run survivors: {', '.join(c for c, r in to.items() if r['dropped'] == 'no')}",
           f"filled-run survivors: {', '.join(c for c, r in tn.items() if r['dropped'] == 'no')}", ""]
    (NEW / "comparison_with_first_run.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
